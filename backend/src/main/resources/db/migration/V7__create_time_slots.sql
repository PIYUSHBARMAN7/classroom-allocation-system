CREATE TABLE time_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    label VARCHAR(60) NOT NULL,
    day_of_week INTEGER NOT NULL,

    start_time TIME WITHOUT TIME ZONE NOT NULL,
    end_time TIME WITHOUT TIME ZONE NOT NULL,

    slot_type VARCHAR(20) NOT NULL,

    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT time_slots_label_not_blank
        CHECK (LENGTH(TRIM(label)) > 0),

    CONSTRAINT time_slots_day_valid
        CHECK (day_of_week BETWEEN 1 AND 7),

    CONSTRAINT time_slots_time_order_valid
        CHECK (
            start_time < end_time
            AND end_time < TIME '24:00:00'
        ),

    CONSTRAINT time_slots_minute_precision
        CHECK (
            EXTRACT(SECOND FROM start_time) = 0
            AND EXTRACT(SECOND FROM end_time) = 0
        ),

    CONSTRAINT time_slots_type_valid
        CHECK (slot_type IN ('TEACHING', 'BREAK')),

    CONSTRAINT time_slots_version_valid
        CHECK (version >= 0),

    CONSTRAINT time_slots_period_unique
        UNIQUE (day_of_week, start_time, end_time),

    CONSTRAINT time_slots_no_active_overlap
        EXCLUDE USING gist (
            int4range(
                day_of_week,
                day_of_week + 1,
                '[)'
            ) WITH &&,

            int4range(
                EXTRACT(EPOCH FROM start_time)::INTEGER,
                EXTRACT(EPOCH FROM end_time)::INTEGER,
                '[)'
            ) WITH &&
        )
        WHERE (enabled)
);