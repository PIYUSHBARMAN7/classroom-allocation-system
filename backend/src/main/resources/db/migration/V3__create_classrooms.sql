CREATE TABLE classrooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(30) NOT NULL,
    name VARCHAR(100) NOT NULL,
    building VARCHAR(100) NOT NULL,
    floor_number INTEGER NOT NULL,

    capacity INTEGER NOT NULL,
    room_type VARCHAR(30) NOT NULL,

    has_projector BOOLEAN NOT NULL DEFAULT FALSE,
    accessible BOOLEAN NOT NULL DEFAULT FALSE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,

    version BIGINT NOT NULL DEFAULT 0,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT classrooms_code_unique
        UNIQUE (code),

    CONSTRAINT classrooms_code_format
        CHECK (code ~ '^[A-Z0-9][A-Z0-9_-]{0,29}$'),

    CONSTRAINT classrooms_name_not_blank
        CHECK (LENGTH(TRIM(name)) > 0),

    CONSTRAINT classrooms_building_not_blank
        CHECK (LENGTH(TRIM(building)) > 0),

    CONSTRAINT classrooms_floor_valid
        CHECK (floor_number BETWEEN -10 AND 200),

    CONSTRAINT classrooms_capacity_valid
        CHECK (capacity BETWEEN 1 AND 2000),

    CONSTRAINT classrooms_room_type_valid
        CHECK (
            room_type IN (
                'LECTURE_HALL',
                'COMPUTER_LAB',
                'SCIENCE_LAB',
                'SEMINAR_ROOM'
            )
        ),

    CONSTRAINT classrooms_version_valid
        CHECK (version >= 0)
);