CREATE TABLE sections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(30) NOT NULL,
    name VARCHAR(100) NOT NULL,
    program_code VARCHAR(30) NOT NULL,
    department VARCHAR(100) NOT NULL,

    semester INTEGER NOT NULL,
    academic_year_start INTEGER NOT NULL,
    student_count INTEGER NOT NULL,

    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT sections_identity_unique
        UNIQUE (
            program_code,
            academic_year_start,
            semester,
            code
        ),

    CONSTRAINT sections_code_format
        CHECK (
            code ~ '^[A-Z0-9][A-Z0-9_-]{0,29}$'
        ),

    CONSTRAINT sections_program_code_format
        CHECK (
            program_code ~ '^[A-Z0-9][A-Z0-9_-]{0,29}$'
        ),

    CONSTRAINT sections_name_not_blank
        CHECK (LENGTH(TRIM(name)) > 0),

    CONSTRAINT sections_department_not_blank
        CHECK (LENGTH(TRIM(department)) > 0),

    CONSTRAINT sections_semester_valid
        CHECK (semester BETWEEN 1 AND 12),

    CONSTRAINT sections_academic_year_valid
        CHECK (academic_year_start BETWEEN 2000 AND 2200),

    CONSTRAINT sections_student_count_valid
        CHECK (student_count BETWEEN 1 AND 2000),

    CONSTRAINT sections_version_valid
        CHECK (version >= 0)
);