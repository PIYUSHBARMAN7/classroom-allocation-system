CREATE TABLE allocation_drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(120) NOT NULL,

    -- The backend supplies the authenticated user's email.
    created_by VARCHAR(254) NOT NULL,

    version BIGINT NOT NULL DEFAULT 0,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT allocation_drafts_name_not_blank
        CHECK (LENGTH(TRIM(name)) > 0),

    CONSTRAINT allocation_drafts_creator_not_blank
        CHECK (LENGTH(TRIM(created_by)) > 0),

    CONSTRAINT allocation_drafts_version_valid
        CHECK (version >= 0)
);


-- Preserve every selected requirement, including those
-- whose sessions could not all be allocated.
CREATE TABLE allocation_draft_requirements (
    draft_id BIGINT NOT NULL,

    requirement_id BIGINT NOT NULL,

    sessions_requested INTEGER NOT NULL,

    periods_per_session INTEGER NOT NULL,

    PRIMARY KEY (draft_id, requirement_id),

    CONSTRAINT draft_requirements_draft_fk
        FOREIGN KEY (draft_id)
        REFERENCES allocation_drafts(id)
        ON DELETE CASCADE,

    CONSTRAINT draft_requirements_requirement_fk
        FOREIGN KEY (requirement_id)
        REFERENCES class_requirements(id)
        ON DELETE RESTRICT,

    CONSTRAINT draft_requirements_sessions_valid
        CHECK (sessions_requested BETWEEN 1 AND 20),

    CONSTRAINT draft_requirements_periods_valid
        CHECK (periods_per_session BETWEEN 1 AND 4)
);


CREATE TABLE allocation_draft_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    draft_id BIGINT NOT NULL,
    requirement_id BIGINT NOT NULL,

    session_number INTEGER NOT NULL,

    room_id BIGINT NOT NULL,
    teacher_id BIGINT NOT NULL,
    section_id BIGINT NOT NULL,

    day_of_week INTEGER NOT NULL,

    start_time TIME NOT NULL,
    end_time TIME NOT NULL,

    CONSTRAINT draft_sessions_requirement_fk
        FOREIGN KEY (draft_id, requirement_id)
        REFERENCES allocation_draft_requirements(
            draft_id,
            requirement_id
        )
        ON DELETE CASCADE,

    CONSTRAINT draft_sessions_room_fk
        FOREIGN KEY (room_id)
        REFERENCES classrooms(id)
        ON DELETE RESTRICT,

    CONSTRAINT draft_sessions_teacher_fk
        FOREIGN KEY (teacher_id)
        REFERENCES teachers(id)
        ON DELETE RESTRICT,

    CONSTRAINT draft_sessions_section_fk
        FOREIGN KEY (section_id)
        REFERENCES sections(id)
        ON DELETE RESTRICT,

    CONSTRAINT draft_sessions_number_valid
        CHECK (session_number BETWEEN 1 AND 20),

    CONSTRAINT draft_sessions_day_valid
        CHECK (day_of_week BETWEEN 1 AND 7),

    CONSTRAINT draft_sessions_time_valid
        CHECK (
            start_time < end_time
            AND end_time < TIME '24:00:00'
        ),

    CONSTRAINT draft_sessions_minute_precision
        CHECK (
            EXTRACT(SECOND FROM start_time) = 0
            AND EXTRACT(SECOND FROM end_time) = 0
        ),

    CONSTRAINT draft_sessions_unique_session
        UNIQUE (draft_id, requirement_id, session_number)
);


CREATE INDEX allocation_drafts_created_at_idx
    ON allocation_drafts (created_at DESC, id DESC);

CREATE INDEX draft_requirements_requirement_idx
    ON allocation_draft_requirements (requirement_id);

CREATE INDEX draft_sessions_schedule_idx
    ON allocation_draft_sessions (
        draft_id,
        day_of_week,
        start_time
    );

CREATE INDEX draft_sessions_room_idx
    ON allocation_draft_sessions (room_id);

CREATE INDEX draft_sessions_teacher_idx
    ON allocation_draft_sessions (teacher_id);

CREATE INDEX draft_sessions_section_idx
    ON allocation_draft_sessions (section_id);