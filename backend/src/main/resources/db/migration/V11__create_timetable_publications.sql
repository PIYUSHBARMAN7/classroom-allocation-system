CREATE TABLE timetable_publications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    source_draft_id BIGINT NOT NULL,
    source_draft_version BIGINT NOT NULL,

    name VARCHAR(120) NOT NULL,

    active BOOLEAN NOT NULL DEFAULT FALSE,

    published_by VARCHAR(254) NOT NULL,
    published_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT timetable_publication_draft_fk
        FOREIGN KEY (source_draft_id)
        REFERENCES allocation_drafts(id)
        ON DELETE RESTRICT,

    CONSTRAINT timetable_publication_source_unique
        UNIQUE (source_draft_id, source_draft_version),

    CONSTRAINT timetable_publication_name_valid
        CHECK (LENGTH(TRIM(name)) > 0),

    CONSTRAINT timetable_publication_creator_valid
        CHECK (LENGTH(TRIM(published_by)) > 0),

    CONSTRAINT timetable_publication_version_valid
        CHECK (source_draft_version >= 0)
);


-- At most one campus timetable can be active.
CREATE UNIQUE INDEX timetable_publications_one_active_idx
    ON timetable_publications (active)
    WHERE active = TRUE;


CREATE TABLE published_timetable_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    publication_id BIGINT NOT NULL,

    requirement_id BIGINT NOT NULL,
    session_number INTEGER NOT NULL,

    room_id BIGINT NOT NULL,
    teacher_id BIGINT NOT NULL,
    section_id BIGINT NOT NULL,

    -- Preserve display labels as they were when published.
    subject_name VARCHAR(100) NOT NULL,
    room_code VARCHAR(30) NOT NULL,
    teacher_name VARCHAR(100) NOT NULL,
    section_code VARCHAR(30) NOT NULL,

    day_of_week INTEGER NOT NULL,

    start_time TIME NOT NULL,
    end_time TIME NOT NULL,

    CONSTRAINT published_session_publication_fk
        FOREIGN KEY (publication_id)
        REFERENCES timetable_publications(id)
        ON DELETE RESTRICT,

    CONSTRAINT published_session_requirement_fk
        FOREIGN KEY (requirement_id)
        REFERENCES class_requirements(id)
        ON DELETE RESTRICT,

    CONSTRAINT published_session_room_fk
        FOREIGN KEY (room_id)
        REFERENCES classrooms(id)
        ON DELETE RESTRICT,

    CONSTRAINT published_session_teacher_fk
        FOREIGN KEY (teacher_id)
        REFERENCES teachers(id)
        ON DELETE RESTRICT,

    CONSTRAINT published_session_section_fk
        FOREIGN KEY (section_id)
        REFERENCES sections(id)
        ON DELETE RESTRICT,

    CONSTRAINT published_session_unique
        UNIQUE (
            publication_id,
            requirement_id,
            session_number
        ),

    CONSTRAINT published_session_number_valid
        CHECK (session_number BETWEEN 1 AND 20),

    CONSTRAINT published_session_day_valid
        CHECK (day_of_week BETWEEN 1 AND 7),

    CONSTRAINT published_session_time_valid
        CHECK (
            start_time < end_time
            AND end_time < TIME '24:00:00'
        ),

    CONSTRAINT published_session_minute_precision
        CHECK (
            EXTRACT(SECOND FROM start_time) = 0
            AND EXTRACT(SECOND FROM end_time) = 0
        )
);


CREATE INDEX published_sessions_teacher_idx
    ON published_timetable_sessions (
        publication_id,
        teacher_id,
        day_of_week,
        start_time
    );

CREATE INDEX published_sessions_section_idx
    ON published_timetable_sessions (
        publication_id,
        section_id,
        day_of_week,
        start_time
    );


-- The publication service will lock this single row
-- to serialize competing publication requests.
CREATE TABLE timetable_publication_lock (
    id INTEGER PRIMARY KEY,

    CONSTRAINT timetable_publication_lock_singleton
        CHECK (id = 1)
);

