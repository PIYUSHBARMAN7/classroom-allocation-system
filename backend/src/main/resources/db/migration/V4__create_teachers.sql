CREATE TABLE teachers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    employee_code VARCHAR(30) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    department VARCHAR(100) NOT NULL,

    user_id BIGINT,

    max_periods_per_day INTEGER NOT NULL DEFAULT 6,
    max_periods_per_week INTEGER NOT NULL DEFAULT 24,

    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT teachers_employee_code_unique
        UNIQUE (employee_code),

    CONSTRAINT teachers_employee_code_format
        CHECK (
            employee_code ~ '^[A-Z0-9][A-Z0-9_-]{0,29}$'
        ),

    CONSTRAINT teachers_full_name_not_blank
        CHECK (LENGTH(TRIM(full_name)) > 0),

    CONSTRAINT teachers_department_not_blank
        CHECK (LENGTH(TRIM(department)) > 0),

    CONSTRAINT teachers_user_unique
        UNIQUE (user_id),

    CONSTRAINT teachers_user_fk
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT teachers_daily_limit_valid
        CHECK (max_periods_per_day BETWEEN 1 AND 12),

    CONSTRAINT teachers_weekly_limit_valid
        CHECK (max_periods_per_week BETWEEN 1 AND 60),

    CONSTRAINT teachers_version_valid
        CHECK (version >= 0)
);