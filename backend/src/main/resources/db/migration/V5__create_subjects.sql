CREATE TABLE subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(30) NOT NULL,
    name VARCHAR(100) NOT NULL,
    department VARCHAR(100) NOT NULL,
    required_room_type VARCHAR(30) NOT NULL,

    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT subjects_code_unique
        UNIQUE (code),

    CONSTRAINT subjects_code_format
        CHECK (code ~ '^[A-Z0-9][A-Z0-9_-]{0,29}$'),

    CONSTRAINT subjects_name_not_blank
        CHECK (LENGTH(TRIM(name)) > 0),

    CONSTRAINT subjects_department_not_blank
        CHECK (LENGTH(TRIM(department)) > 0),

    CONSTRAINT subjects_room_type_valid
        CHECK (
            required_room_type IN (
                'LECTURE_HALL',
                'COMPUTER_LAB',
                'SCIENCE_LAB',
                'SEMINAR_ROOM'
            )
        ),

    CONSTRAINT subjects_version_valid
        CHECK (version >= 0)
);