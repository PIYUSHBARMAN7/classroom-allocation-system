CREATE TABLE class_requirements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    section_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    teacher_id BIGINT NOT NULL,

    sessions_per_week INTEGER NOT NULL,
    periods_per_session INTEGER NOT NULL DEFAULT 1,

    requires_projector BOOLEAN NOT NULL DEFAULT FALSE,
    requires_accessible_room BOOLEAN NOT NULL DEFAULT FALSE,

    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT requirements_section_fk
        FOREIGN KEY (section_id)
        REFERENCES sections(id)
        ON DELETE RESTRICT,

    CONSTRAINT requirements_subject_fk
        FOREIGN KEY (subject_id)
        REFERENCES subjects(id)
        ON DELETE RESTRICT,

    CONSTRAINT requirements_teacher_fk
        FOREIGN KEY (teacher_id)
        REFERENCES teachers(id)
        ON DELETE RESTRICT,

    CONSTRAINT requirements_section_subject_unique
        UNIQUE (section_id, subject_id),

    CONSTRAINT requirements_sessions_valid
        CHECK (sessions_per_week BETWEEN 1 AND 20),

    CONSTRAINT requirements_periods_valid
        CHECK (periods_per_session BETWEEN 1 AND 4),

    CONSTRAINT requirements_version_valid
        CHECK (version >= 0)
);

CREATE INDEX requirements_teacher_idx
    ON class_requirements (teacher_id);

CREATE INDEX requirements_subject_idx
    ON class_requirements (subject_id);